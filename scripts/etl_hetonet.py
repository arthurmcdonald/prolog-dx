import argparse
import csv
import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def open_text(path):
    path = Path(path)
    if path.suffix == ".gz":
        return gzip.open(path, "rt", encoding="utf-8", newline="")
    return open(path, "rt", encoding="utf-8", newline="")


def atom(text):
    """Quote a string as a Prolog atom."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def strip_kind(node_id):
    """Convert 'Disease::DOID:1234' to 'DOID:1234'"""
    return node_id.split("::", 1)[1] if "::" in node_id else node_id


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--nodes", default=ROOT / "data/raw/hetionet-v1.0-nodes.tsv")
    ap.add_argument("--edges", default=ROOT / "data/raw/hetionet-v1.0-edges.sif.gz")
    ap.add_argument("--out", default=ROOT / "data/kb/hetionet_kb.pl")
    args = ap.parse_args()

    diseases, symptoms = {}, {}
    with open_text(args.nodes) as file_out:
        for row in csv.DictReader(file_out, delimiter="\t"):
            if row["kind"] == "Disease":
                diseases[row["id"]] = row["name"].strip().lower()
            elif row["kind"] == "Symptom":
                symptoms[row["id"]] = row["name"].strip().lower()

    edges = set()
    with open_text(args.edges) as file_out:
        for row in csv.DictReader(file_out, delimiter="\t"):
            if row["metaedge"] != "DpS":
                continue
            d, s = row["source"], row["target"]
            if d in diseases and s in symptoms:
                edges.add((d, s))

    if not edges:
        sys.exit("no DpS edges found: check the --nodes and --edges files")

    used_diseases = sorted({d for d, _ in edges})
    used_symptoms = sorted({s for _, s in edges})

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as file_out:
        file_out.write("% GENERATED by scripts/etl_hetionet.py -- do not edit.\n")
        file_out.write("kb_meta(source, 'Hetionet v1.0 DpS edges (Zhou et al. 2014 symptom-disease network)').\n")
        file_out.write("kb_meta(license, 'CC0-1.0').\n")
        file_out.write("kb_meta(url, 'https://github.com/hetio/hetionet').\n\n")
        for d in used_diseases:
            file_out.write(f"disease({atom(strip_kind(d))}, {atom(diseases[d])}).\n")
        file_out.write("\n")
        for s in used_symptoms:
            file_out.write(f"symptom({atom(strip_kind(s))}, {atom(symptoms[s])}).\n")
        file_out.write("\n")
        for d, s in sorted(edges):
            file_out.write(f"presents({atom(strip_kind(d))}, {atom(strip_kind(s))}).\n")

    print(f"wrote {out}: {len(used_diseases)} diseases, {len(used_symptoms)} symptoms, {len(edges)} edges")


if __name__ == "__main__":
    main()
